def card_markdown(p):
    out = [f"# {p['id']} · {p['name']}", "", "这是一张候选项目蓝图，不代表独立软件已经开发、测试通过或取得业务效果。", "",
           f"分类：{p['category']} · {p['categoryName']}  ",
           f"准备度：{READINESS_LABELS[p['readiness']]}  ",
           "相关复盘节点：" + "、".join(f"{h}年" for h in p["horizons"]) + "（不是连续开发年限）  ",
           f"资料基线：{BASELINE}", ""]
    groups = [("目标用户", "audience"), ("具体问题", "problem"), ("现有替代方案", "alternatives"),
              ("为什么与你有关", "personalFit"), ("启动条件", "trigger"), ("第一版范围", "firstVersion"),
              ("输入", "inputs"), ("输出", "outputs"), ("本版不做", "nonGoals"), ("验收", "acceptance"),
              ("继续条件", "continueWhen"), ("停止或暂缓条件", "stopWhen")]
    for label, key in groups:
        out += [f"## {label}", ""]
        v = p[key]
        out += [f"- {x}" for x in v] if isinstance(v, list) else [v]
        out += [""]
    out += ["## 依据与边界", "", *[source_line(sid) for sid in p["sourceIds"]], "", "## 可直接交给Codex的提示词", "", "```text", p["prompt"].rstrip(), "```", ""]
    return "\n".join(out)


