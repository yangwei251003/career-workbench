def validate_catalog(catalog):
    assert len(PROJECTS) == 40
    assert [p["id"] for p in PROJECTS] == [f"{i:02}" for i in range(1, 41)]
    assert [p["name"] for p in PROJECTS] == NAMES
    required = {"id", "name", "category", "categoryName", "readiness", "horizons", "audience", "problem", "alternatives", "personalFit", "trigger", "inputs", "outputs", "nonGoals", "acceptance", "continueWhen", "stopWhen", "firstVersion", "sourceIds", "prompt"}
    arrays = {"horizons", "inputs", "outputs", "nonGoals", "acceptance", "sourceIds"}
    for p in PROJECTS:
        assert set(p) == required, p["id"]
        assert all(isinstance(p[k], str) and p[k] for k in required - arrays), p["id"]
        assert all(isinstance(p[k], list) and p[k] for k in arrays), p["id"]
        assert set(p["horizons"]) <= {1, 2, 5, 10}
        assert set(p["sourceIds"]) <= set(SOURCE_BY_ID)
        assert p["name"] in p["prompt"] and "验收场景：" in p["prompt"] and "停止/暂缓条件：" in p["prompt"]
    for c in CAPABILITIES:
        assert all(isinstance(c[k], str) for k in ("name", "focus", "proof"))
    for o in OPPORTUNITIES:
        assert all(isinstance(o[k], str) for k in ("title", "evidence", "inference", "risk"))
        assert isinstance(o["signals"], list)
    assert all(s["date"] <= BASELINE for s in SOURCES)
    json.dumps(catalog, ensure_ascii=False, allow_nan=False)


def main():
    for p in PROJECTS:
        p["prompt"] = prompt_for(p)
    catalog = dict(profile=PROFILE, projects=PROJECTS, sources=SOURCES,
                   roadmap=ROADMAP, capabilities=CAPABILITIES, opportunities=OPPORTUNITIES)
    validate_catalog(catalog)
    seed = make_seed()
    catalog_dir = ROOT / "catalog"
    docs_dir = ROOT / "docs"
    cards_dir = docs_dir / "项目卡"
    catalog_dir.mkdir(parents=True, exist_ok=True)
    cards_dir.mkdir(parents=True, exist_ok=True)
    for name, data in [("catalog.json", catalog), ("seed.json", seed)]:
        target = catalog_dir / name
        target.write_text(json.dumps(data, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
        assert json.loads(target.read_text(encoding="utf-8")) == data
    for p in PROJECTS:
        (cards_dir / f"{p['id']}_{p['name']}.md").write_text(card_markdown(p), encoding="utf-8")
    (docs_dir / "项目总索引.md").write_text(make_index(), encoding="utf-8")
    (docs_dir / "十年职业路线.md").write_text(make_roadmap(), encoding="utf-8")
    print(json.dumps({"projects": len(PROJECTS), "cards": len(list(cards_dir.glob('*.md'))),
                      "categories": len(CATEGORIES), "sources": len(SOURCES),
                      "evidence": len(seed["evidence"]), "facts": len(seed["facts"]),
                      "decisions": len(seed["decisions"]), "liveDataModified": False}, ensure_ascii=False))


if __name__ == "__main__":
    main()


